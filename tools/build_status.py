#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate wiki/Build-Status.md by actually running things.

deploy.py calls this, so the page always shows what was true at deploy time.
"""

import datetime
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from src import __version__

ENV = dict(os.environ, PYTHONIOENCODING="utf-8", PYTHONUTF8="1")
INDIA = datetime.timezone(datetime.timedelta(hours=5, minutes=30))
TIMEOUT = 40

# Not run by the interpreter here, and why.
NOT_RUN = {
    "file_processor.kpl": "needs a file name on the command line",
    "mashables.kpl": "uses live data; covered offline by the test suite",
}


def run(*args):
    """(returncode, stdout, stderr); returncode None on timeout."""
    try:
        r = subprocess.run(args, cwd=ROOT, env=ENV, capture_output=True, encoding="utf-8",
                           errors="replace", timeout=TIMEOUT, stdin=subprocess.DEVNULL)
        return r.returncode, r.stdout.strip(), r.stderr.strip()
    except subprocess.TimeoutExpired:
        return None, "", "timed out"


def python(*args):
    return run(sys.executable, *args)


def cell(text):
    return text.replace("|", "\\|").replace("\n", " ")


def normalise(output):
    # Display only: the C runtime prints lists without commas and true/false
    # in lower case.
    return output.replace(",", "").replace("True", "true").replace("False", "false")


def first_difference(interpreted, compiled):
    a, b = normalise(interpreted).splitlines(), normalise(compiled).splitlines()
    for x, y in zip(a, b):
        if x != y:
            return f"`{cell(x)}` vs `{cell(y)}`"
    return f"{len(a)} lines vs {len(b)} lines"


def example_row(path):
    name = path.name
    rel = f"examples/{name}"

    compiled_rc, compiled_out, compiled_err = python("kapilac.py", rel, "-r")
    refused = compiled_rc == 1 and re.match(r".*?:\d+: ", compiled_err)
    llvm_rc, _, _ = python("kapilac.py", rel, "--emit-llvm")
    llvm = "emits IR" if llvm_rc == 0 else "fails"

    if name in NOT_RUN:
        interpreted = f"not run: {NOT_RUN[name]}"
        interp_rc, interp_out = None, None
    else:
        interp_rc, interp_out, _ = python("kapila.py", rel)
        interpreted = "runs" if interp_rc == 0 else "fails"

    if refused:
        compiled = f"refused: {cell(compiled_err.split(': ', 1)[1])}"
        verdict = "refused"
    elif name in NOT_RUN:
        compiled = "builds" if compiled_rc == 0 else "not run standalone"
        verdict = "skipped"
    elif compiled_rc != 0 or interp_rc != 0:
        compiled = "fails" if compiled_rc != 0 else "runs"
        verdict = "failing"
    elif normalise(compiled_out) == normalise(interp_out):
        compiled = "runs, same output"
        verdict = "agree"
    else:
        compiled = f"runs, **differs**: {first_difference(interp_out, compiled_out)}"
        verdict = "differ"

    return verdict, f"| `{name}` | {interpreted} | {compiled} | {llvm} |"


def tests_summary():
    rc, out, err = python("-m", "pytest", "-q")
    last = out.splitlines()[-1] if out else err
    return rc == 0, re.sub(r"=+", "", last).strip()


def git(*args):
    return run("git", *args)[1]


def artifact(path):
    p = ROOT / path
    if not p.exists():
        return None
    when = datetime.datetime.fromtimestamp(p.stat().st_mtime, INDIA).strftime("%d %B %Y, %H:%M")
    return f"{p.stat().st_size / 1e6:.1f} MB, built {when}"


def main():
    rows, verdicts = [], []
    for path in sorted((ROOT / "examples").glob("*.kpl")):
        verdict, row = example_row(path)
        verdicts.append(verdict)
        rows.append(row)

    passed, tests = tests_summary()
    dirty = len([l for l in git("status", "--porcelain").splitlines() if l.strip()])
    commit = git("log", "-1", "--format=%h %s")
    gui = artifact("static/downloads/kapila-gui-windows-x64.exe")
    now = datetime.datetime.now(INDIA).strftime("%d %B %Y, %H:%M")
    count = verdicts.count

    lines = [
        "# Build status",
        "",
        f"Generated by `tools/build_status.py` on {now} (India time), at deploy. "
        "Everything below comes from running the code, so don't edit this page by hand.",
        "",
        "| | |",
        "|---|---|",
        f"| Version | {__version__} |",
        f"| Tests | {'passing' if passed else '**failing**'}: {cell(tests)} |",
        f"| Last commit | {cell(commit)} |",
        f"| Uncommitted changes | {dirty} files |",
        f"| Desktop app | {gui or 'not built'} |",
        "",
        "## Examples through each engine",
        "",
        f"{len(verdicts)} example programs. Same output interpreted and compiled: {count('agree')}. "
        f"Refused by the compiler: {count('refused')}. Different output: {count('differ')}. "
        f"Failing: {count('failing')}. Skipped: {count('skipped')}.",
        "",
        "| Program | Interpreter | Compiled through C | LLVM |",
        "|---|---|---|---|",
        *rows,
        "",
        "In the LLVM column, *emits IR* means only that IR was generated. The output hasn't been "
        "run yet. See the [compiler roadmap](Compiler-Roadmap).",
        "",
    ]
    out = ROOT / "wiki" / "Build-Status.md"
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{out.relative_to(ROOT)}: {count('agree')} agree, {count('refused')} refused, "
          f"{count('skipped')} skipped, {count('differ')} differ, {count('failing')} failing; {cell(tests)}")


if __name__ == "__main__":
    main()
